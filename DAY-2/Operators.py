# Arithmetic
a = 15
b = 4
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a ** b)
print(a // b)

# Comparison
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

# Logical
x = True
y = False
print(x and y)
print(x or y)
print(not x)

# Assignment
marks = 50
marks += 10
marks -= 5
marks *= 2
marks /= 5
marks %= 3
marks **= 2
marks //= 2
print(marks)

# Membership
languages = ["Python", "Java", "C++"]
print("Python" in languages)
print("JavaScript" not in languages)

# Identity
a = [1, 2, 3]
b = a
c = [1, 2, 3]

print(a is b)
print(a is c)
print(a == c)