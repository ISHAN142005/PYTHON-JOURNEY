# Assignment Operators

score = 20

print("Initial Score:", score)

score += 5
print("After += :", score)

score -= 3
print("After -= :", score)

score *= 2
print("After *= :", score)

score /= 4
print("After /= :", score)

score %= 3
print("After %= :", score)

score **= 2
print("After **= :", score)

score //= 2
print("After //= :", score)